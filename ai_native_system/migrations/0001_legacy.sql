-- The ai_native schema is provisioned for a separate migration role.
-- Keep serialized legacy data as text so stored JSON and timestamps round-trip exactly.
CREATE TABLE ai_native.principals (
    tenant text NOT NULL,
    id text NOT NULL,
    roles text NOT NULL,
    active bigint NOT NULL DEFAULT 1,
    PRIMARY KEY (tenant, id)
);

CREATE TABLE ai_native.objects (
    tenant text NOT NULL,
    id text NOT NULL,
    type text NOT NULL,
    state text NOT NULL,
    version bigint NOT NULL,
    properties text NOT NULL,
    links text NOT NULL,
    PRIMARY KEY (tenant, id)
);

CREATE TABLE ai_native.knowledge (
    tenant text NOT NULL,
    id text NOT NULL,
    version bigint NOT NULL,
    text text NOT NULL,
    PRIMARY KEY (tenant, id)
);

CREATE TABLE ai_native.knowledge_history (
    tenant text NOT NULL,
    id text NOT NULL,
    version bigint NOT NULL,
    text text NOT NULL,
    PRIMARY KEY (tenant, id, version)
);

CREATE TABLE ai_native.tasks (
    id text PRIMARY KEY,
    tenant text NOT NULL,
    application text NOT NULL,
    object_id text NOT NULL,
    requester text NOT NULL,
    request_key text NOT NULL,
    definition_hash text NOT NULL,
    status text NOT NULL,
    next_stage bigint NOT NULL DEFAULT 0,
    grounding_hash text,
    proposal text,
    approver text,
    approval_hash text,
    UNIQUE (tenant, requester, request_key)
);

CREATE TABLE ai_native.legacy_task_order (
    task_id text PRIMARY KEY REFERENCES ai_native.tasks(id),
    row_id bigint NOT NULL UNIQUE
);

CREATE TABLE ai_native.steps (
    task_id text NOT NULL REFERENCES ai_native.tasks(id),
    stage bigint NOT NULL,
    agent_id text NOT NULL,
    proposal text NOT NULL,
    PRIMARY KEY (task_id, stage)
);

CREATE TABLE ai_native.events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id text NOT NULL REFERENCES ai_native.tasks(id),
    time text NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    event text NOT NULL,
    detail text NOT NULL
);
CREATE INDEX events_by_task ON ai_native.events (task_id, id);

CREATE TABLE ai_native.execution_claims (
    task_id text PRIMARY KEY REFERENCES ai_native.tasks(id),
    token text NOT NULL,
    expires double precision NOT NULL
);

CREATE TABLE ai_native.remote_operations (
    operation_id text PRIMARY KEY REFERENCES ai_native.tasks(id),
    tool_name text NOT NULL,
    tool_version text NOT NULL,
    adapter_identity text NOT NULL,
    payload text NOT NULL,
    status text NOT NULL,
    response text,
    attempts bigint NOT NULL DEFAULT 0
);

CREATE TABLE ai_native.effects (
    operation_id text PRIMARY KEY REFERENCES ai_native.tasks(id),
    action text NOT NULL,
    object_id text NOT NULL,
    receipt text NOT NULL
);

CREATE TABLE ai_native.sqlite_imports (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    snapshot_digest text NOT NULL,
    imported_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
